import { existsSync, mkdirSync, writeFileSync } from "fs";
import { join } from "path";
import type { GitForgeDriver } from "../drivers/driver.interface.ts";

export async function handleActionCommand(driver: GitForgeDriver, args: string[]): Promise<void> {
  const subAction = args[0] || "list";

  switch (subAction) {
    case "add":
    case "create": {
      const templateName = args[1];
      if (!templateName || templateName === "container-build" || templateName === "container" || templateName === "docker" || templateName === "podman") {
        await scaffoldContainerBuildWorkflow(driver);
      } else {
        console.error(`Unknown action template: "${templateName}". Available: container-build`);
        process.exit(1);
      }
      break;
    }

    case "list":
    default: {
      console.log(`
\x1b[34m[tycho-forge]\x1b[0m Action & Workflow Templates:

  \x1b[36mcontainer-build\x1b[0m    Build Containerfile/Dockerfile and publish to OCI Registry (${driver.context.host || "git.qtrn.io"})
  \x1b[36mci-lint\x1b[0m            Automated validation, lint and typecheck

Usage:
  tycho forge action add container-build
`);
      break;
    }
  }
}

async function scaffoldContainerBuildWorkflow(driver: GitForgeDriver): Promise<void> {
  const host = driver.context.host || "git.qtrn.io";
  const isForgejo = driver.forgeType === "forgejo" || host.includes("qtrn.io");
  const targetDir = isForgejo ? ".forgejo/workflows" : ".github/workflows";
  const filePath = join(process.cwd(), targetDir, "build-container.yml");

  const containerFile = existsSync(join(process.cwd(), "Containerfile"))
    ? "./Containerfile"
    : existsSync(join(process.cwd(), "Dockerfile"))
    ? "./Dockerfile"
    : "./Containerfile";

  const workflowYaml = `# ==============================================================================
# Sovereign Container Build & OCI Publish Workflow
# Generated by Tycho Forge
# Target Registry: ${host}
# ==============================================================================

name: Build & Publish Container Image

on:
  push:
    branches:
      - main
      - develop
    tags:
      - 'v*'
  pull_request:
    branches:
      - main

jobs:
  build-and-push:
    name: Build & Push OCI Container
    runs-on: native
    steps:
      - name: Checkout Source Code
        uses: actions/checkout@v4

      - name: Set up Docker Buildx
        uses: docker/setup-buildx-action@v3
        continue-on-error: true

      - name: Authenticate with OCI Registry (${host})
        uses: docker/login-action@v3
        with:
          registry: ${host}
          username: \${{ github.actor }}
          password: \${{ secrets.GITHUB_TOKEN }}

      - name: Extract OCI Metadata (Tags & Labels)
        id: meta
        uses: docker/metadata-action@v5
        with:
          images: ${host}/\${{ github.repository }}
          tags: |
            type=raw,value=latest,enable=\${{ github.ref == 'refs/heads/main' }}
            type=ref,event=branch
            type=semver,pattern={{version}}
            type=sha,format=short

      - name: Build and Push OCI Image
        uses: docker/build-push-action@v6
        with:
          context: .
          file: ${containerFile}
          push: \${{ github.event_name != 'pull_request' }}
          tags: \${{ steps.meta.outputs.tags }}
          labels: \${{ steps.meta.outputs.labels }}
`;

  mkdirSync(join(process.cwd(), targetDir), { recursive: true });
  writeFileSync(filePath, workflowYaml, "utf-8");

  console.log(`\x1b[32m✔\x1b[0m Generated container build workflow: \x1b[1m${targetDir}/build-container.yml\x1b[0m`);
  console.log(`Target Registry: \x1b[36m${host}/\${{ github.repository }}\x1b[0m`);
  console.log(`Container definition: \x1b[36m${containerFile}\x1b[0m`);
}
